# ===== 1. 什么是表达式 =====
# 表达式（Expression）：由「值、变量、运算符」组合而成，写出来后它“能算出一个结果”。
# 语句（Statement）：是让程序“做一件事的指令”，例如把某个值存进变量。
#
# 区别：
#   2 + 3          -> 这是一个表达式，它的值是 5
#   x = 2 + 3      -> 这是一个“赋值语句”，它把 5 存进 x，本身没有“要返回的值”
#
# 直觉理解：表达式像“一道数学题（有答案）”，语句像“一道命令（去执行）”。

expr_value = 2 + 3          # 2 + 3 是表达式
assign_stmt = "x = 2 + 3"   # x = 2 + 3 是语句（这里把它写成字符串仅作展示）

print("【什么是表达式】")
print("2 + 3 这个表达式的值是：", 2 + 3)
print("x = 2 + 3 是赋值语句，作用是把 5 存进变量 x，本身没有返回值。")
print()


# ===== 2. 表达式都有“值” =====
# 任何表达式在 Python 里都会被“求值”成一个具体的值。
# 用 print() 把各种表达式的结果打印出来，你就能看到它们的“值”。

print("【表达式都有值】")
print("算术表达式 2 + 3 * 4 的值：", 2 + 3 * 4)        # 先乘后加 = 14
print("字符串表达式 'a' 的值：", "a")                   # 字符串本身也是表达式
print("布尔表达式 1 < 2 的值：", 1 < 2)                 # 比较表达式，值为 True
print("变量也是表达式，x 的值：", expr_value)
print()


# ===== 3. 常见表达式类型 =====
# 3.1 算术表达式
print("【算术表达式】")
print("加法 10 + 5 =", 10 + 5)
print("除法（得到小数） 10 / 4 =", 10 / 4)
print("整除（丢余数） 10 // 4 =", 10 // 4)
print("取余（求余数） 10 % 4 =", 10 % 4)
print("幂运算 2 ** 10 =", 2 ** 10)

# 3.2 字符串表达式：拼接（+）与重复（*）
print("\n【字符串表达式】")
print("拼接 'Hello' + ' ' + 'World' =", "Hello" + " " + "World")
print("重复 '嘀' * 3 =", "嘀" * 3)
name = "小明"
print("变量参与拼接 '你好，' + name =", "你好，" + name)

# 3.3 比较表达式：结果永远是一个布尔值 True 或 False
print("\n【比较表达式】")
print("5 > 3 的结果是：", 5 > 3)
print("5 == 5 的结果是：", 5 == 5)
print("'apple' < 'banana' 的结果是：", "apple" < "banana")  # 按字母顺序比较

# 3.4 逻辑表达式：把多个条件用 and / or / not 组合
print("\n【逻辑表达式】")
print("True and False =", True and False)
print("True or False =", True or False)
print("not (1 > 2) =", not (1 > 2))
print("年龄判断 (18 >= 18) and (18 <= 65) =", (18 >= 18) and (18 <= 65))
print()


# ===== 4. 求值顺序与括号 =====
# Python 运算符有默认的“优先级”和“结合性”：
#   - 优先级：先乘除后加减，比较和逻辑更靠后。
#   - 括号 () 永远最优先，可以强制改变计算顺序。
# 直觉：不确定顺序时，加括号最稳妥，也最易读。

print("【求值顺序与括号】")
print("不加括号 2 + 3 * 4 =", 2 + 3 * 4)          # 先算 3*4，再加 2 -> 14
print("加括号 (2 + 3) * 4 =", (2 + 3) * 4)        # 先算 2+3，再乘 4 -> 20
print("逻辑混合 1 < 2 and 3 > 4 or 5 == 5 =", 1 < 2 and 3 > 4 or 5 == 5)
print("加括号更清晰 (1 < 2) and ((3 > 4) or (5 == 5)) =", (1 < 2) and ((3 > 4) or (5 == 5)))
print()


# ===== 5. 条件表达式（三元表达式） =====
# 当你想“根据条件选一个值”时，用一行条件表达式很方便：
#   值 = a if 条件 else b
# 意思是：条件成立取 a，否则取 b。
# 它本身就是“表达式”，所以能直接拿来给变量赋值或放进 print()。

print("【条件表达式（三元表达式）】")
age = 20
# 写法一：用 if 语句（多行）
status = ""
if age >= 18:
    status = "成年"
else:
    status = "未成年"
print("用 if 语句得到 status =", status)

# 写法二：用条件表达式（一行，更简洁）
status2 = "成年" if age >= 18 else "未成年"
print("用条件表达式得到 status2 =", status2)

# 直接参与运算
score = 85
result = "及格" if score >= 60 else "不及格"
print("成绩", score, "的判定是：", result)
print()


# ===== 6. 链式比较 =====
# Python 支持“链式比较”，可以像数学里一样连续写：
#   0 < x < 10  等价于  x > 0 and x < 10
# 很多其他语言（如 C / Java）不支持这种写法，必须拆成两段用 and 连接。

print("【链式比较】")
x = 7
print("链式比较 0 < x < 10 (x=7) 的结果：", 0 < x < 10)
print("等价写法 x > 0 and x < 10 的结果：", x > 0 and x < 10)
x = 15
print("x=15 时 0 < x < 10 的结果：", 0 < x < 10)
print("链式比较也可以三段连写 0 <= x < 100：", 0 <= x < 100)
print()


# ===== 7. 表达式在 f-string 中的运用 =====
# f-string 里可以直接写表达式，Python 会先求值再插入字符串。
# 两种常用写法：
#   f"{2 + 3}"      -> 只插入结果 "5"
#   f"{2 + 3 =}"    -> 同时显示“表达式=结果”，即 "2 + 3 =5"（调试超好用）

print("【表达式在 f-string 中】")
a, b = 2, 3
print(f"直接插入结果：2 + 3 = {2 + 3}")
print(f"显示表达式与结果：{2 + 3 =}")             # 注意 = 号写法
print(f"变量参与：{a} + {b} = {a + b}")
print(f"字符串重复：{'*' * 5}")
print(f"条件表达式也能用：{('大' if a > b else '小')}")
print()


# ===== 8. 简单认识 eval() =====
# eval() 可以“把一个字符串当成 Python 表达式来求值”：
#   eval("2 + 3 * 4")  -> 14
# ⚠️ 安全提醒：绝对不要对“用户输入”或“外部不可信数据”使用 eval()！
#   因为用户输入可以写任意代码（例如删文件、偷密码），会造成严重安全问题。
#   日常练习或已知可信内容时才可用，生产代码里基本要避免。

print("【eval() 简介（了解即可）】")
print("eval('2 + 3 * 4') 的结果：", eval("2 + 3 * 4"))
print("⚠️ 警告：不要用 eval() 处理任何用户输入或不可信数据。")
print()


