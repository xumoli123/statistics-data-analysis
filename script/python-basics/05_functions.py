# ============================================================
# 1. 定义与调用：def、函数名、缩进块、调用
# ============================================================
print("===== 1. 定义与调用 =====")

# 用 def 关键字定义函数，函数名后用圆括号 () 放参数，
# 冒号 : 结尾，函数体必须缩进（推荐 4 个空格）。
def say_hi():
    """一个最简单的函数：没有参数，也没有返回值。"""
    print(" hi ~ 这是一个没有参数的函数")


# 定义不会执行函数体，只有“调用”才会执行。
say_hi()
print("→ 定义函数 = 造工具；调用函数 = 使用工具。\n")


# ============================================================
# 2. 参数：位置参数、关键字参数、默认参数
# ============================================================
print("===== 2. 参数 =====")


# 2.1 位置参数：按先后顺序传值
def make_tea(name, sugar):
    """根据茶名和糖分做一杯茶。"""
    print(f" 制作了一杯 {name}，糖分等级：{sugar}")


make_tea("绿茶", "半糖")      # 按顺序：name="绿茶", sugar="半糖"
print("→ 位置参数按从左到右的顺序一一对应。\n")


# 2.2 关键字参数：调用时写 参数名=值，顺序可打乱
make_tea(sugar="无糖", name="红茶")
print("→ 关键字参数更清晰，还能不按顺序传。\n")


# 2.3 默认参数：给参数设默认值（注意：有默认值的参数必须放在后面）
def make_coffee(name="美式", size="中杯"):
    """制作咖啡，name 和 size 都有默认值。"""
    print(f" 制作了一杯 {size} {name}")


make_coffee()                  # 都用默认值
make_coffee("拿铁")            # 只改 name
make_coffee(size="大杯")       # 只改 size（用关键字参数）
print("→ 默认参数让函数调用更省事，但默认参数必须写在普通参数之后。\n")


# ============================================================
# 3. 返回值：return、返回多个值、没有 return 返回 None
# ============================================================
print("===== 3. 返回值 =====")


# 3.1 return 返回单个值
def add(a, b):
    """返回 a 与 b 的和。"""
    return a + b


result = add(3, 5)
print(f" add(3, 5) 的返回值是：{result}")


# 3.2 返回多个值（本质是返回一个元组，再用解包接收）
def divmod_result(a, b):
    """返回 a 除以 b 的商和余数。"""
    return a // b, a % b


quotient, remainder = divmod_result(17, 5)
print(f" 17 ÷ 5 的商={quotient}，余数={remainder}")
print("→ 函数用逗号返回多个值，实际是返回了一个元组，再用变量解包接收。\n")


# 3.3 没有 return 时返回 None
def do_nothing():
    """什么都不返回。"""
    pass


value = do_nothing()
print(f" 没有 return 的函数，返回值是：{value}（即 None）")
print("→ 没有显式 return，函数默认返回 None。\n")


# ============================================================
# 4. 作用域：局部变量 vs 全局变量
# ============================================================
print("===== 4. 作用域 =====")

counter = 0  # 全局变量：在函数外定义


def increment_local():
    """局部变量演示：函数内的变量只在函数内可见。"""
    counter = 10  # 这里的 counter 是局部变量，和外部的全局 counter 无关
    print(f" 函数内部的 counter = {counter}")


increment_local()
print(f" 函数外部的 counter = {counter}（未被函数改变）")
print("→ 函数内新建的同名变量是局部变量，不会影响到全局变量。\n")


# 演示 global（谨慎使用）：真的想改全局变量时的写法
def increment_global():
    """用 global 声明后，才能修改全局变量。"""
    global counter
    counter = counter + 1


increment_global()
print(f" 使用 global 后，全局 counter = {counter}")
print("→ global 会破坏函数的独立性，能不用就不用，避免滥用。\n")


# ============================================================
# 5. 文档字符串 docstring 与函数注释习惯
# ============================================================
print("===== 5. 文档字符串 docstring =====")


def celsius_to_fahrenheit(celsius):
    """
    将摄氏度转换为华氏度。

    参数:
        celsius (float): 摄氏温度
    返回:
        float: 华氏温度
    """
    return celsius * 9 / 5 + 32


print(f" 0°C = {celsius_to_fahrenheit(0):.1f}°F")
print("→ 用三引号写的 docstring 是给人和工具看的“说明书”，可用 help(函数名) 查看。\n")


