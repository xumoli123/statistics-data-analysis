# 8. 递归初体验：阶乘（进阶小节）
# ============================================================
print("===== 8. 递归初体验（阶乘） =====")


def factorial(n: int) -> int:
    """
    计算 n 的阶乘（n! = n × (n-1) × ... × 1）。

    递归两大要素：
        1) 基线条件（base case）：n == 1 时直接返回 1，停止递归；
        2) 递归调用：把问题缩小为 factorial(n-1)，向基线条件逼近。
    """
    if n == 1:            # 基线条件：最简单的情况，必须能停止
        return 1
    return n * factorial(n - 1)  # 递归调用：自己调用自己，规模更小


print(f" factorial(5) = {factorial(5)}（即 5×4×3×2×1 = 120）")
print("→ 写递归务必先想清楚“什么时候停”，否则会无限递归导致报错。\n")


