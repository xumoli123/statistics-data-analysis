# ===== 1. 什么是变量 =====
# 变量可以理解为一个“贴了标签的盒子”。
# 盒子用来装数据，标签（变量名）用来找到这个盒子。
# 例如 x = 10，意思是把数字 10 放进名叫 x 的盒子里。
# 之后我们只要说“x”，程序就知道指的是 10。

# ===== 2. 变量赋值与重新赋值 =====
x = 10
print("赋值后 x =", x)

# 同一个变量可以装新的数据，这叫“重新赋值”
x = 20
print("重新赋值后 x =", x)

# ===== 3. 变量命名规则 =====
# 合法命名示例（下面这些都能正常运行）：
name = "小明"
age_1 = 18
_total = 100  # 下划线开头也允许

# 不合法命名（仅作说明，不要真的写进代码运行）：
# 2name = "小红"   # 数字不能开头
# my-name = 5      # 不能包含连字符
# class = 3        # class 是 Python 关键字，不能做变量名

# 命名建议：见名知意，用全小写 + 下划线（蛇形命名）
user_count = 0
print("user_count =", user_count)

# ===== 4. 基本数据类型初识：int、float、str、bool =====
num_int = 10          # 整数 int
num_float = 3.14      # 浮点数 float
text = "你好"          # 字符串 str
is_student = True    # 布尔值 bool

print("num_int 的类型是", type(num_int))
print("num_float 的类型是", type(num_float))
print("text 的类型是", type(text))
print("is_student 的类型是", type(is_student))

# ===== 5. 动态类型特性演示 =====
# Python 是动态类型语言：同一个变量可以先装数字，再装文字。
value = 100
print("动态类型演示：初始 value =", value, "，类型是", type(value))
value = "现在变成字符串了"
print("动态类型演示：之后 value =", value, "，类型是", type(value))

# ===== 6. 多重赋值与交换变量 =====
a = 1
b = 2
print("交换前：a =", a, "，b =", b)
# 一行同时为多个变量赋值
a, b = b, a
print("交换后：a =", a, "，b =", b)

# 多重赋值也可以一次性创建多个变量
c, d, e = 3, 4, 5
print("多重赋值：c =", c, "，d =", d, "，e =", e)

# ===== 7. 常量的约定（全大写）=====
# Python 没有真正的“常量”，约定用全大写表示“不应被修改的值”。
PI = 3.14159
MAX_SCORE = 100
print("常量 PI =", PI, "，MAX_SCORE =", MAX_SCORE)

# ===== 8. f-string 初步体验 =====
# f-string 是在字符串前加 f，用 {变量} 把值嵌入文字里。
name = "小明"
age = 18
print(f"{name} 今年 {age} 岁。")
